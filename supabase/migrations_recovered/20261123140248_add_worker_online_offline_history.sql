
create table if not exists public.srk_worker_availability_events (
  id uuid primary key default gen_random_uuid(),
  worker_id uuid not null references public.srk_worker_profiles(id) on delete restrict,
  previous_is_online boolean not null,
  new_is_online boolean not null,
  changed_at timestamptz not null default clock_timestamp(),
  latitude double precision,
  longitude double precision,
  actor_user_id uuid,
  change_source text not null default 'technician_app',
  constraint srk_worker_availability_transition_changed check (previous_is_online <> new_is_online),
  constraint srk_worker_availability_latitude_valid check (latitude is null or latitude between -90 and 90),
  constraint srk_worker_availability_longitude_valid check (longitude is null or longitude between -180 and 180),
  constraint srk_worker_availability_source_valid check (change_source in ('technician_app','admin_or_system'))
);

create index if not exists srk_worker_availability_events_worker_time_idx
  on public.srk_worker_availability_events(worker_id, changed_at desc);

alter table public.srk_worker_availability_events enable row level security;
revoke all on public.srk_worker_availability_events from public, anon, authenticated;
grant select on public.srk_worker_availability_events to authenticated;

drop policy if exists srk_worker_availability_events_participant_read on public.srk_worker_availability_events;
create policy srk_worker_availability_events_participant_read
on public.srk_worker_availability_events
for select to authenticated
using (
  exists (
    select 1 from public.srk_worker_profiles w
    where w.id = srk_worker_availability_events.worker_id
      and w.user_id = (select auth.uid())
  )
  or public.srk_has_admin_permission('workers.verify')
  or public.srk_has_admin_permission('workers.manage')
);

create or replace function public.srk_log_worker_availability_change()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $function$
begin
  if old.is_online is distinct from new.is_online then
    insert into public.srk_worker_availability_events (
      worker_id, previous_is_online, new_is_online, changed_at,
      latitude, longitude, actor_user_id, change_source
    ) values (
      new.id, old.is_online, new.is_online, clock_timestamp(),
      case when new.is_online then new.location_lat else null end,
      case when new.is_online then new.location_lng else null end,
      auth.uid(),
      case when auth.uid() = new.user_id then 'technician_app' else 'admin_or_system' end
    );
  end if;
  return new;
end;
$function$;

revoke all on function public.srk_log_worker_availability_change() from public, anon, authenticated;
drop trigger if exists trg_srk_log_worker_availability_change on public.srk_worker_profiles;
create trigger trg_srk_log_worker_availability_change
after update of is_online on public.srk_worker_profiles
for each row
when (old.is_online is distinct from new.is_online)
execute function public.srk_log_worker_availability_change();

comment on table public.srk_worker_availability_events is
'Append-only history of each Technician/Helper Online-Offline transition. Current state remains srk_worker_profiles.is_online; events are generated by a database trigger.';
comment on column public.srk_worker_profiles.is_online is
'Current Online/Offline availability state; every state transition is recorded in srk_worker_availability_events.';
